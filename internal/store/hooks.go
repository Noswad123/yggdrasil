type HookStatus struct {
	Path       string
	State      string
	Executable string
	Original   bool
}

type hookManifest struct {
	Version                             int
	Common, DataRoot, Store, Executable string
	Original                            bool
	OriginalHash                        string
	OriginalMode                        os.FileMode
}

func (m *Manager) hookPaths() (string, string, string) {
	d := filepath.Join(m.common, "hooks")
	return filepath.Join(d, "post-checkout"), filepath.Join(d, ".ygg-post-checkout.json"), filepath.Join(d, "post-checkout.ygg-original")
}

// Unlike sourceGit, this probe must honor actual global/system/includes and
// worktree config. Only config-location Git variables survive; command-line
// config injection is diagnosed rather than silently concealed.
func (m *Manager) hooksConfigured() (bool, error) {
	for _, key := range []string{"GIT_CONFIG_COUNT", "GIT_CONFIG_PARAMETERS"} {
		if _, ok := os.LookupEnv(key); ok {
			return false, fmt.Errorf("cannot inspect hooks with %s overrides; unset it and retry", key)
		}
	}
	b, err := m.sourceGit("rev-parse", "--absolute-git-dir")
	if err != nil {
		return false, err
	}
	cmd := exec.Command("git", "--git-dir="+strings.TrimSuffix(string(b), "\n"), "--work-tree="+m.worktree, "config", "--includes", "--get-all", "core.hooksPath")
	cmd.Dir = m.worktree
	for _, e := range os.Environ() {
		key := strings.SplitN(e, "=", 2)[0]
		if !strings.HasPrefix(strings.ToUpper(key), "GIT_") || key == "GIT_CONFIG_GLOBAL" || key == "GIT_CONFIG_SYSTEM" || key == "GIT_CONFIG_NOSYSTEM" {
			cmd.Env = append(cmd.Env, e)
		}
	}
	// No stderr/config contents are exposed. git config does not run hooks or
	// fsmonitor, and no -c override masks the setting being inspected.
	err = cmd.Run()
	if err == nil {
		return true, nil
	}
	var exit *exec.ExitError
	if errors.As(err, &exit) && exit.ExitCode() == 1 {
		return false, nil
	}
	return false, errors.New("cannot read effective Git hook configuration")
}

func hookFile(p string) ([]byte, os.FileMode, bool, error) {
	if err := checkPath(p, true, false); err != nil {
		return nil, 0, false, err
	}
	st, err := os.Lstat(p)
	if os.IsNotExist(err) {
		return nil, 0, false, nil
	}
	if err != nil {
		return nil, 0, false, err
	}
	if !st.Mode().IsRegular() {
		return nil, 0, false, errors.New("hook metadata must be regular files")
	}
	b, err := os.ReadFile(p)
	return b, st.Mode(), true, err
}

func hookHash(b []byte) string   { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }
func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", "'\"'\"'") + "'" }

// Moving an ordinary hook changes its $0/own path. Hooks which locate resources
// relative to their own filename may need manual integration instead.
func (m *Manager) hookScript(h hookManifest) []byte {
	_, _, backup := m.hookPaths()
	s := "#!/bin/sh\n# yggdrasil managed post-checkout v1; do not edit\nstatus=0\n"
	if h.Original && h.OriginalMode&0111 != 0 {
		s += "if [ -f " + shellQuote(backup) + " ] && [ ! -L " + shellQuote(backup) + " ] && [ -x " + shellQuote(backup) + " ]; then\n  " + shellQuote(backup) + " \"$@\"\n  status=$?\nelse\n  printf '%s\\n' 'yggdrasil: original hook is missing or unsafe; inspect manually' >&2\nfi\n"
	}
	s += "if [ \"${3-}\" = 1 ]; then\n  if [ -f " + shellQuote(h.Executable) + " ] && [ -x " + shellQuote(h.Executable) + " ]; then\n    " + shellQuote(h.Executable) + " --data-root " + shellQuote(h.DataRoot) + " hook-post-checkout --common-dir " + shellQuote(h.Common) + " \"$@\"\n    if [ $? -ne 0 ]; then\n      printf '%s\\n' 'yggdrasil: post-checkout attach failed' >&2\n    fi\n  else\n    printf '%s\\n' 'yggdrasil: pinned hook executable is missing or not executable' >&2\n  fi\nfi\nexit \"$status\"\n"
	return []byte(s)
}

func hookManager(b []byte) bool {
	s := strings.ToLower(string(b))
	for _, marker := range []string{"husky", "lefthook", "pre-commit", "pre_commit", "overcommit", "simple-git-hooks", "yggdrasil managed", "git-hooks", "git lfs post-checkout", "generated by", "do not edit", "hookman"} {
		if strings.Contains(s, marker) {
			return true
		}
	}
	return false
}

// inspectHooks validates ownership without consulting or opening the private store.
func (m *Manager) inspectHooks() (HookStatus, hookManifest, error) {
	p, meta, backup := m.hookPaths()
	s := HookStatus{Path: p, State: "not-installed"}
	var h hookManifest
	b, mode, exists, err := hookFile(p)
	if err != nil {
		return s, h, err
	}
	mb, mm, managed, err := hookFile(meta)
	if err != nil {
		return s, h, err
	}
	ob, om, original, err := hookFile(backup)
	if err != nil {
		return s, h, err
	}
	if !managed {
		if original || (exists && hookManager(b)) {
			s.State = "modified/partial"
			return s, h, errors.New("unexpected hook backup or hook manager; inspect manually before integration")
		}
		return s, h, nil
	}
	s.State = "modified/partial"
	if json.Unmarshal(mb, &h) != nil || h.Version != 1 {
		return s, h, errors.New("invalid hook ownership manifest; inspect manually")
	}
	s.Executable = h.Executable
	s.Original = h.Original
	if h.Common != m.common || h.DataRoot != m.dataRoot || h.Store != m.root {
		return s, h, errors.New("hook belongs to a different store/data root; uninstall using its original data root before reinstalling")
	}
	if !filepath.IsAbs(h.Executable) || mm != 0600 || !exists || mode != 0755 || !bytes.Equal(b, m.hookScript(h)) || original != h.Original || (original && (hookHash(ob) != h.OriginalHash || om != h.OriginalMode)) || (!original && (h.OriginalHash != "" || h.OriginalMode != 0)) {
		return s, h, errors.New("hook wrapper, manifest or backup modified/partial; inspect manually")
	}
	s.State = "installed"
	return s, h, nil
}

func (m *Manager) HooksStatus() (HookStatus, error) {
	s, _, err := m.inspectHooks()
	if err != nil {
		return s, err
	}
	configured, err := m.hooksConfigured()
	if err != nil {
		return s, err
	}
	if configured && s.State == "installed" {
		s.State = "bypassed"
	}
	return s, nil
}

func hookExecutable(p string) (string, error) {
	if !filepath.IsAbs(p) {
		return "", errors.New("hook executable must be an absolute stable path")
	}
	p, err := realPath(p)
	if err != nil {
		return "", err
	}
	if err = regular(p); err != nil {
		return "", err
	}
	st, err := os.Stat(p)
	if err != nil {
		return "", err
	}
	if st.Mode().Perm()&0111 == 0 {
		return "", errors.New("hook executable is not executable")
	}
	for _, part := range strings.Split(filepath.ToSlash(p), "/") {
		if strings.HasPrefix(part, "go-build") {
			return "", errors.New("go run executables are temporary; install a stable binary first")
		}
	}
	return p, nil
}

func (m *Manager) hookLock() (func(), error) {
	if err := checkPath(m.common, false, false); err != nil {
		return nil, err
	}
	p := filepath.Join(m.common, ".ygg-post-checkout.lock")
	f, err := os.OpenFile(p, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return nil, errors.New("hooks locked or lock unavailable; stale locks must be inspected manually")
	}
	if err = f.Close(); err != nil {
		return nil, err
	}
	return func() { _ = os.Remove(p) }, nil
}

// publishHook stages a complete file, then links it exclusively into place.
// Existing destinations are never overwritten, even during partial recovery.
func publishHook(p string, b []byte, mode os.FileMode) error {
	f, err := os.CreateTemp(filepath.Dir(p), ".ygg-hook-stage-")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(b); err != nil {
		f.Close()
		return err
	}
	if err = f.Chmod(mode); err != nil {
		f.Close()
		return err
	}
	if err = f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	return os.Link(f.Name(), p)
}

func (m *Manager) InstallHooks(executable string, dryRun bool) (HookStatus, error) {
	exe, err := hookExecutable(executable)
	if err != nil {
		return HookStatus{}, err
	}
	preflight := func() (HookStatus, hookManifest, error) {
		s, h, e := m.inspectHooks()
		if e != nil {
			return s, h, e
		}
		if _, e = m.load(); e != nil {
			return s, h, e
		}
		configured, e := m.hooksConfigured()
		if e != nil {
			return s, h, e
		}
		if configured {
			return s, h, errors.New("core.hooksPath is configured; manual integration required (no Git config was changed)")
		}
		if s.State == "installed" && h.Executable != exe {
			return s, h, errors.New("hook executable differs; uninstall then reinstall with the new executable")
		}
		return s, h, nil
	}
	s, _, err := preflight()
	if err != nil || s.State == "installed" {
		return s, err
	}
	if dryRun {
		s.State = "installed"
		s.Executable = exe
		_, _, s.Original, err = hookFile(s.Path)
		return s, err
	}
	unlock, err := m.hookLock()
	if err != nil {
		return s, err
	}
	defer unlock()
	s, _, err = preflight()
	if err != nil || s.State == "installed" {
		return s, err
	}
	p, meta, backup := m.hookPaths()
	if err = checkPath(filepath.Dir(p), true, false); err != nil {
		return s, err
	}
	if err = os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		return s, err
	}
	b, mode, original, err := hookFile(p)
	if err != nil {
		return s, err
	}
	h := hookManifest{Version: 1, Common: m.common, DataRoot: m.dataRoot, Store: m.root, Executable: exe, Original: original}
	if original {
		h.OriginalHash = hookHash(b)
		h.OriginalMode = mode
		if err = os.Link(p, backup); err != nil {
			return s, err
		}
	}
	mb, err := json.MarshalIndent(h, "", "  ")
	if err != nil {
		return s, err
	}
	if err = publishHook(meta, append(mb, '\n'), 0600); err != nil {
		return s, err
	}
	if original {
		if err = os.Remove(p); err != nil {
			return s, err
		}
	}
	if err = publishHook(p, m.hookScript(h), 0755); err != nil {
		return s, err
	}
	return m.HooksStatus()
}

func (m *Manager) UninstallHooks(dryRun bool) (HookStatus, error) {
	s, _, err := m.inspectHooks()
	if err != nil || s.State == "not-installed" {
		return s, err
	}
	if dryRun {
		s.State = "not-installed"
		s.Executable = ""
		s.Original = false
		return s, nil
	}
	unlock, err := m.hookLock()
	if err != nil {
		return s, err
	}
	defer unlock()
	s, h, err := m.inspectHooks()
	if err != nil || s.State == "not-installed" {
		return s, err
	}
	p, meta, backup := m.hookPaths()
	if err = os.Remove(p); err != nil {
		return s, err
	}
	if h.Original {
		if err = os.Link(backup, p); err != nil {
			return s, err
		}
		if err = os.Remove(backup); err != nil {
			return s, err
		}
	}
	if err = os.Remove(meta); err != nil {
		return s, err
	}
	return HookStatus{Path: p, State: "not-installed"}, nil
}

func (m *Manager) AttachFromHook(expectedCommon string) error {
	if !filepath.IsAbs(expectedCommon) {
		return errors.New("hook common directory must be canonical and absolute")
	}
	p, err := realPath(expectedCommon)
	if err != nil {
		return err
	}
	if p != expectedCommon || p != m.common {
		return errors.New("hook source common directory identity mismatch")
	}
	return m.Attach()
}
